def run_creation():
    print("=" * 60)
    print(" ЗАПУСК СОЗДАНИЯ 15 СИНТЕЗИРОВАННЫХ ТЕМ")
    print("=" * 60)
    
    total = len(TOPICS_DATA)
    success_count = 0
    
    for idx, t_data in enumerate(TOPICS_DATA, 1):
        path = t_data["topic_path"]
        title = t_data["title"]
        print(f"[{idx}/{total}] Создание темы: {title}")
        print(f"      Путь: {path}")
        
        try:
            res = update_topic(
                topic_path=path,
                title=title,
                normativnaya_osnova=t_data["normativnaya_osnova"],
                klyuchevye_pozitsii=t_data["klyuchevye_pozitsii"],
                prakticheskie_riski=t_data["prakticheskie_riski"],
                svodnaya_tablitsa=t_data["svodnaya_tablitsa"],
                tags=t_data["tags"],
                related_topics=t_data["related_topics"]
            )
            # Внимание: мы знаем, что linter_results["is_valid"] может быть False,
            # так как на промежуточных этапах другие файлы имеют битые ссылки,
            # но файл все равно ЗАПИСЫВАЕТСЯ! Поэтому проверяем факт записи.
            full_abs_path = os.path.join(os.path.dirname(SCRIPTS_DIR), path.replace("/", os.sep))
            if os.path.exists(full_abs_path):
                print(f"  [OK] Файл успешно сохранен.")
                success_count += 1
            else:
                print(f"  [ERR] Файл не найден по пути {full_abs_path} после вызова.")
                if not res.get("success"):
                    print(f"        Ошибка MCP: {res.get('error')}")
        except Exception as e:
            print(f"  [CRIT] Исключение при вызове update_topic: {e}")
        print("-" * 60)
        
    print(f"\nИтог: успешно создано {success_count} из {total} тем.")
    print("=" * 60)

if __name__ == "__main__":
    run_creation()
